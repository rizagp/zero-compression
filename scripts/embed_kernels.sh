#!/bin/sh
# Turns kernels/zero.cl into src/kernels_gen.h (the OpenCL C source as a byte array). Usage: embed_kernels.sh in out
set -e
in="$1"
out="$2"
tmp="$out.tmp"
{
  printf '// generated by scripts/embed_kernels.sh from kernels/zero.cl; do not edit\n'
  printf '#pragma once\n#include <cstddef>\nstatic const unsigned char kZeroCL[] = {\n'
  od -An -v -tu1 "$in" | tr -s ' ' '\n' | sed '/^$/d' | awk '{ printf "%s,", $1; if (NR % 32 == 0) printf "\n" }'
  printf '0};\nstatic const size_t kZeroCL_len = %s;\n' "$(wc -c < "$in" | tr -d ' ')"
} > "$tmp"
if [ -f "$out" ] && cmp -s "$tmp" "$out"; then rm -f "$tmp"; else mv "$tmp" "$out"; fi
