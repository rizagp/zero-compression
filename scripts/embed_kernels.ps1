# Turns kernels\zero.cl into src\kernels_gen.h: the OpenCL C source as a byte array, so the exe needs no files.
param([Parameter(Mandatory = $true)][string]$Source, [Parameter(Mandatory = $true)][string]$Header)
$ErrorActionPreference = 'Stop'
$bytes = [IO.File]::ReadAllBytes($Source)
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("// generated by scripts/embed_kernels.ps1 from kernels/zero.cl; do not edit`n")
[void]$sb.Append("#pragma once`n#include <cstddef>`nstatic const unsigned char kZeroCL[] = {`n")
for ($i = 0; $i -lt $bytes.Length; $i++) {
  [void]$sb.Append($bytes[$i])
  [void]$sb.Append(',')
  if (($i % 32) -eq 31) { [void]$sb.Append("`n") }
}
[void]$sb.Append("0};`nstatic const size_t kZeroCL_len = $($bytes.Length);`n")
$new = $sb.ToString()
if ((Test-Path $Header) -and ([IO.File]::ReadAllText($Header) -eq $new)) { return }  # (unchanged: no rebuild of the header's users)
[IO.File]::WriteAllText($Header, $new)
